UNKNOWN = ("страна не определена", "", "")
COAST_STATION = ("береговая станция", "", "")


def _emoji(iso2: str) -> str:
    """Флаг-эмодзи из кода страны: две региональные буквы."""
    if len(iso2) != 2 or not iso2.isalpha():
        return ""
    return "".join(chr(0x1F1E6 + ord(letter) - ord("A")) for letter in iso2.upper())


def flag_for_mmsi(mmsi) -> tuple:
    """Возвращает (страна, ISO-код, флаг-эмодзи) по MMSI.

    Служебные номера (береговые станции, рации, SAR, EPIRB) страны не имеют —
    для них возвращается понятное пояснение, а не выдуманная страна.
    """
    digits = "".join(ch for ch in str(mmsi or "") if ch.isdigit())
    if len(digits) < 3:
        return UNKNOWN
    if digits.startswith("0"):
        return COAST_STATION
    if digits.startswith("111"):
        return ("спасательная служба (SAR)", "", "")
    if digits[:2] in ("98", "99"):
        return ("судно при базовом судне", "", "")
    if digits.startswith("8"):
        return ("радиостанция (носимая)", "", "")
    if digits.startswith("970"):
        return ("воздушное судно SAR", "", "")
    if digits.startswith("972"):
        return ("радиобуй AIS-SART", "", "")
    if digits.startswith("974"):
        return ("аварийный радиобуй EPIRB", "", "")

    country, iso2 = MID_COUNTRIES.get(int(digits[:3]), (UNKNOWN[0], UNKNOWN[1]))
    if not iso2:
        return UNKNOWN
    return (country, iso2, _emoji(iso2))


def country_for_mmsi(mmsi) -> str:
    return flag_for_mmsi(mmsi)[0]


def flag_text(mmsi) -> str:
    """Компактная подпись для таблиц: «🇷🇺 Россия» или просто страна."""
    country, _iso2, emoji = flag_for_mmsi(mmsi)
    return f"{emoji} {country}".strip() if emoji else country
